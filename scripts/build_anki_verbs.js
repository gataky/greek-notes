// Writes exports/anki-verbs.json: the word list's active verbs as Anki cards, for the
// "Greek verb" and "Greek aspect" note types that ../anki-sync pushes (`./sync verbs`).
//   node scripts/build_anki_verbs.js      (make anki-verbs)
//
// Nothing here is new data. Each verb's forms, group and highlighted letters are the aspect
// fork's (aspect-fork.js on verbToShow()'s merge of the dictionary's cells), so the cards show
// what the verb tables and aspect forks pages show. The cloze sentences are the tense and
// aspect drill's past-tense ones (aspect-sentences.json), with the answer found the way the
// drill finds it.
//
// Verbs come out in the aspect forks page's group order, regular groups first and irregular
// last, so Anki's new-card queue follows it. The file is committed, so a diff shows which cards
// a push will change.

const fs = require("fs");
const path = require("path");
const VF = require("../docs/javascripts/verb-forms.js");
const AF = require("../docs/javascripts/aspect-fork.js");
const AD = require("../docs/javascripts/aspect-drill.js");
const VD = require("../docs/javascripts/voice-drill.js");

const DATA = path.join(__dirname, "../docs/data");
const OUT = path.join(__dirname, "../exports/anki-verbs.json");
const read = file => JSON.parse(fs.readFileSync(path.join(DATA, file), "utf8"));
const sheet = read("verbs.json");
const forms = read("verb-forms.json");
const sentences = read("aspect-sentences.json").filter(s => s.tense === "past");

// Groups whose aorist doesn't look like the present, so reading it needs its own card.
const RECOGNIZE = new Set(["irregular", "strong", "no-perf"]);
const REASONS = {
  once: "a single, finished action",
  repeated: "a habit or repeated action",
  ongoing: "in progress at the time",
};
const groupOrder = new Map(AF.GROUPS.map((g, i) => [g.id, i]));
const problems = [];

// "*answered*" marks the verb in the drill's English; the card doesn't need the marks.
const unmark = en => en.replace(/\*/g, "");

// The answer word in a Greek sentence, wrapped as a cloze with the dictionary form as its
// hint. The drill's answersIn() gives it lowercased, so it's found again in the original text
// to keep a capital at the start of the sentence.
function cloze(s, conjugation) {
  const cell = AD.CELLS.find(c => c.tense === "past" && c.aspect === s.aspect);
  const answers = AD.answersIn(s.el, AD.formsOf(conjugation), cell, s.person);
  if (answers.length !== 1) return null;
  const words = [...s.el.matchAll(/[\p{L}\p{M}]+/gu)].filter(m => VD.lower(m[0]) === answers[0]);
  if (words.length !== 1) return null;
  const { index } = words[0], word = words[0][0];
  return `${s.el.slice(0, index)}{{c1::${word}::${s.verb}}}${s.el.slice(index + word.length)}`;
}

const verbs = [];
const clozes = [];
const seen = new Set();
sheet.forEach((entry, sheetIndex) => {
  if (entry.voice !== "active" || seen.has(entry.greek)) return;
  seen.add(entry.greek);
  const shown = VF.verbToShow(entry.greek, { sheet, forms });
  const fork = shown && AF.analyse(shown.conjugation, shown.verb);
  if (!fork || fork.group === "missing") {
    problems.push(`${entry.greek}: the dictionary and the word list don't give its past and future forms, so it has no card`);
    return;
  }
  const group = AF.GROUP[fork.group];
  const generated = Object.entries(fork.generated).filter(([, g]) => g).map(([cell]) => cell);
  const notes = [...fork.notes];
  if (generated.length) notes.push(`Not in the dictionary, so generated by rule: the ${generated.join(", ")}.`);

  const own = sentences.filter(s => s.verb === entry.greek);
  const example = own.find(s => s.aspect === "simple") || own[0];
  for (const s of own) {
    const text = cloze(s, shown.conjugation);
    if (!text) {
      problems.push(`${entry.greek}: can't find the answer in "${s.el}"`);
      continue;
    }
    clozes.push({
      verb: entry.greek, group: fork.group, order: [groupOrder.get(fork.group), sheetIndex],
      aspect: s.aspect, reason: REASONS[s.reason] || s.reason,
      // The English keeps the drill's *marks* around the verb: the card shows it in bold, so
      // the front says who did it, which the Greek often doesn't.
      el: s.el, en: s.en, text, note: s.note || "",
    });
  }

  const noPerf = fork.group === "no-perf";
  verbs.push({
    greek: entry.greek,
    english: entry.english,
    group: fork.group,
    groupName: group.name,
    groupRule: group.rule,
    // The irregular group's note is written for the aspect forks page, which draws no fork for them.
    groupNote: group.note.replace("These don't get a fork: their stems", "Their stems"),
    order: [groupOrder.get(fork.group), sheetIndex],
    // 1st singular forms, plain and with the fork's highlights as HTML spans.
    present: fork.present ? AF.plainText(fork.present) : entry.greek,
    imperfect: AF.plainText(fork.imperfect),
    aorist: AF.plainText(fork.aorist),
    future: noPerf ? `θα ${AF.plainText(fork.present)}` : `θα ${AF.plainText(fork.dependent)}`,
    marked: {
      present: AF.markHTML(fork.present),
      imperfect: AF.markHTML(fork.imperfect),
      aorist: AF.markHTML(fork.aorist),
      future: AF.markHTML(noPerf ? `θα ${fork.present}` : `θα ${fork.dependent}`),
    },
    notes,
    // The form shown on the recognition card: the aorist, or the only past there is.
    recognize: RECOGNIZE.has(fork.group) ? AF.plainText(noPerf ? fork.imperfect : fork.aorist) : "",
    example: example ? { el: example.el, en: unmark(example.en) } : null,
  });
});

const byOrder = (a, b) => a.order[0] - b.order[0] || a.order[1] - b.order[1];
verbs.sort(byOrder);
// Within a verb, the continuous sentence before the simple one, as the drill pairs them.
clozes.sort((a, b) => byOrder(a, b) || (a.aspect === b.aspect ? 0 : a.aspect === "continuous" ? -1 : 1));
const strip = x => { const { order, ...rest } = x; return rest; };

const groups = AF.GROUPS.filter(g => verbs.some(v => v.group === g.id)).map(({ id, name, rule, note }) => ({ id, name, rule, note }));
// One item per line, like the other data files, so diffs show which cards changed.
const lines = list => list.map(x => JSON.stringify(strip(x))).join(",\n");
const json = `{
"groups": [
${lines(groups)}
],
"verbs": [
${lines(verbs)}
],
"cloze": [
${lines(clozes)}
]
}
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, json);

const counts = {};
verbs.forEach(v => { counts[v.group] = (counts[v.group] || 0) + 1; });
console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${verbs.length} verbs (${verbs.filter(v => v.recognize).length} with a recognition card), ${clozes.length} cloze sentences`);
console.log("  " + groups.map(g => `${g.id} ${counts[g.id]}`).join(", "));
problems.forEach(p => console.log("  ! " + p));
if (problems.length) process.exitCode = 1;
