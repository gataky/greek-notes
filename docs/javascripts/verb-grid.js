// Renders a verb's conjugation grid. Shared by the verb tables and conjugation patterns pages.
// Needs greek-verbs.js loaded first.

(function (root) {
  "use strict";
  const { conjugate } = root.GreekVerbs;

  const DOT = `<span class="dot"> · </span>`;
  // The endings after the slash drop on phones, to keep the person column narrow.
  const PERSON_LABELS = ["εγώ", "εσύ", "αυτός<span class=\"full\">/ή/ό</span>", "εμείς", "εσείς", "αυτοί<span class=\"full\">/ές/ά</span>"];
  const CLASS_ORDER = ["a1", "a2", "b1", "b2", "c1", "c2", "c3", "c4", "irregular"];
  const PATTERN_ENDINGS = { a1: "-ω", a2: "-ω after a vowel", b1: "-άω", b2: "-ώ", c1: "-ομαι", c2: "-άμαι", c3: "-ιέμαι", c4: "-ούμαι", irregular: "irregular" };

  const esc = s => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

  // Letters without accents or diaeresis, lower case, one per letter of the form.
  const letters = s => [...s.replace("|", "")].map(ch => ch.normalize("NFD")[0].toLowerCase());

  // Where a past form's augment is: an ε or η that the same person's form without one (the
  // present for the past continuous, the dependent for the aorist) doesn't have there. Either
  // it's added (έγραψα / γράψω, ήθελα / θέλω), or it's an ε in place of a prefix's last vowel
  // (παρέλαβα / παραλάβω) or an η in place of the first vowel (ήρθα / έρθω). Other changed vowels
  // belong to the stem (πήρες / πάρεις). -1 if there's none.
  function augmentAt(past, base) {
    const p = letters(past), b = letters(base);
    let i = 0;
    while (i < p.length && i < b.length && p[i] === b[i]) i++;
    if (i >= p.length || !"εη".includes(p[i])) return -1;
    const next = p.slice(i + 1, i + 3).join("");
    if (next.length < 2) return -1;
    if (next === b.slice(i, i + 2).join("")) return i;
    const replaces = (p[i] === "ε" && "αοι".includes(b[i])) || (p[i] === "η" && i === 0 && "αε".includes(b[i]));
    return replaces && next === b.slice(i + 1, i + 3).join("") ? i : -1;
  }

  // "θα γράψ|ουμε" → muted "θα", stem, highlighted ending; `aug` highlights that letter of the word.
  function formHTML(form, aug = -1) {
    const space = form.lastIndexOf(" ");
    const pre = space >= 0 ? form.slice(0, space + 1) : "";
    const [stem, end = ""] = form.slice(pre.length).split("|");
    const chars = [...stem];
    const stemHTML = aug >= 0 && aug < chars.length
      ? esc(chars.slice(0, aug).join("")) + `<span class="aug">${esc(chars[aug])}</span>` + esc(chars.slice(aug + 1).join(""))
      : esc(stem);
    return (pre ? `<span class="pre">${esc(pre)}</span>` : "") + stemHTML + (end ? `<span class="end">${esc(end)}</span>` : "");
  }

  // Marks a form the dictionary doesn't have, which the engine generated by rule.
  const GENERATED = `<span class="gen" title="Not in the dictionary: generated by rule" aria-label="generated">*</span>`;

  // Main form, with any alternatives (μιλάω / μιλώ, έγραψαν / γράψανε) in small type underneath.
  // Pass `base` (the same person without an augment) to highlight a past form's augment.
  function cellHTML(alternatives, generated = false, base = "") {
    if (!alternatives.length) return `<span class="dash">—</span>`;
    const one = f => formHTML(f, base ? augmentAt(f, base) : -1);
    const [main, ...rest] = alternatives;
    return one(main) + (generated ? GENERATED : "") + rest.map(a => `<span class="alt">${one(a)}</span>`).join("");
  }

  const dropPrefix = cell => cell.map(row => row.map(f => f.replace(/^θα /, "")));
  const first = cell => (cell[0] && cell[0][0]) || "";
  // "γράφ|ω" → "γράφ"
  const stemOf = cell => (first(cell).includes("|") ? first(cell).split("|")[0] : "");

  // The simple stem, with the letters it doesn't share with the continuous one marked: γρά<b>ψ</b>-.
  function simpleStemHTML(simple, continuous) {
    if (!simple) return "";
    const s = [...simple], a = letters(simple), b = letters(continuous);
    let k = 0;
    while (k < a.length && k < b.length && a[k] === b[k]) k++;
    const rest = s.slice(k).join("");
    return esc(s.slice(0, k).join("")) + (rest ? `<b>${esc(rest)}</b>` : "") + "-";
  }

  // The grid for one verb: heading, then the tenses as a timeline, left to right: the aorist and
  // past continuous, the present, then the continuous and simple futures. The simple stem is on
  // the outside, the continuous one in the middle. Then the imperatives under the futures, the
  // perfects along the same timeline, and the να forms written out. Narrow screens scroll it
  // sideways, with the person column kept in view.
  // Pass `heading` to replace the default verb heading (word, meaning, class and voice tags),
  // and `conjugation` to show forms other than the engine's (see verb-forms.js). A conjugation
  // with `generated` gets the cells the dictionary didn't have marked, with a footnote.
  function cardHTML(verb, { heading, conjugation } = {}) {
    const c = conjugation || conjugate(verb);
    const I = c.indicative;
    const contPresent = I.present.continuous;
    const simplePresent = dropPrefix(I.future.simple);

    const g = c.generated || {};
    const gen = (key, i) => !!(g[key] && g[key][i]);
    const anyGenerated = Object.values(g).some(v => (Array.isArray(v) ? v.some(Boolean) : v));

    // Each column: its forms, the `generated` key they come from, its aspect, its Greek name,
    // and for the pasts the forms without an augment to find it by.
    const COLUMNS = [
      { cells: I.past.simple, key: "past", simple: true, name: "Αόριστος", base: simplePresent },
      { cells: I.past.continuous, key: "imperfect", simple: false, name: "Παρατατικός", base: contPresent },
      { cells: contPresent, key: "present", simple: false, name: "Ενεστώτας" },
      { cells: I.future.continuous, key: "present", simple: false, name: "Εξακολουθητικός Μέλλοντας" },
      { cells: I.future.simple, key: "dependent", simple: true, name: "Στιγμιαίος Μέλλοντας" },
    ];
    // Past | present | future, with a gap between them.
    const row = (who, cols, tag = "td") => `<tr>${who}${cols.map((col, i) => (i === 2 || i === 3 ? `<${tag} class="gap"></${tag}>` : "") + col).join("")}</tr>`;
    const aspect = col => (col.simple ? "simple" : "cont");

    const contStem = stemOf(contPresent);
    const stems = { cont: contStem ? esc(contStem) + "-" : "", simple: simpleStemHTML(stemOf(simplePresent), contStem) };
    const subs = COLUMNS.map(col => `<th class="sub ${aspect(col)}">${col.simple ? "simple" : "continuous"}<small>${col.name}</small>${stems[aspect(col)] ? `<span class="stem">${stems[aspect(col)]}</span>` : ""}</th>`);
    const who = label => `<td class="who">${label}</td>`;
    const rows = PERSON_LABELS.map((label, i) => row(who(label), COLUMNS.map(col =>
      `<td class="${aspect(col)}">${cellHTML(col.cells[i] || [], gen(col.key, i), (col.base && (col.base[i] || [])[0]) || "")}</td>`))).join("");

    // Singular over plural, so a future column is no wider than its forms.
    const imperative = (pair, key) => (pair.some(r => r.length)
      ? pair.map((r, i) => `<span class="imp">${cellHTML(r, gen(key, i))}</span>`).join("")
      : `<span class="dash">—</span>`);
    const imperatives = `<tr class="extra">${who(`imp<span class="full">erative</span><span class="abbr">.</span>`)}<td class="simple"></td><td class="cont"></td><td class="gap"></td><td class="cont"></td><td class="gap"></td>
      <td class="cont">${imperative(c.imperative.continuous, "impCont")}</td><td class="simple">${imperative(c.imperative.simple, "impSimple")}</td></tr>`;
    // The perfects along the timeline: είχα, έχω, θα έχω γράψει.
    const perfect = cell => (first(cell) ? formHTML(first(cell)) + (g.perfect ? GENERATED : "") : `<span class="dash">—</span>`);
    const perfects = `<tr class="extra">${who("perfect")}<td colspan="2">${perfect(I.past.perfect)}</td><td class="gap"></td>
      <td>${perfect(I.present.perfect)}</td><td class="gap"></td><td colspan="2">${perfect(I.future.perfect)}</td></tr>`;

    // After να: the futures' forms without θα, written out with this verb.
    const example = (pre, cell, generated) =>
      `<span class="ex">${first(cell) ? formHTML(pre + first(cell)) + (generated ? GENERATED : "") : `<span class="dash">—</span>`}</span>`;
    const legend = `<dt>After να</dt><dd>${example("να ", contPresent, gen("present", 0))}${DOT}${example("να ", simplePresent, gen("dependent", 0))}</dd>`;
    const genNote = anyGenerated
      ? `<p class="gen-note">${GENERATED} Not in the dictionary, so generated by rule. Double-check these.</p>`
      : "";

    const cls = verb.class || c.pattern;
    const pattern = PATTERN_ENDINGS[c.pattern];
    const classTag = pattern && pattern !== cls ? `${cls} · ${pattern}` : cls;
    return `
      ${heading ?? `<div>
        <div class="verb-top"><h2 lang="el">${esc(c.greek)}</h2><span class="english">${esc(c.english)}</span></div>
        <div class="tags"><span class="tag">${esc(classTag)}</span>${c.voice ? `<span class="tag">${esc(c.voice)}</span>` : ""}</div>
      </div>`}
      ${[verb.note, ...c.notes].filter(Boolean).map(n => `<p class="note">${esc(n)}</p>`).join("")}
      <div class="scroll timeline"><table lang="el">
        <thead>
          <tr><th class="who"></th><th class="group past" colspan="2">← Past</th><th class="gap"></th><th class="group present">Present</th><th class="gap"></th><th class="group future" colspan="2">Future →</th></tr>
          ${row(`<th class="who"></th>`, subs, "th")}
        </thead>
        <tbody>
          ${rows}
          ${imperatives}
          ${perfects}
        </tbody>
      </table></div>
      ${genNote}
      <dl class="legend">${legend}</dl>`;
  }

  root.VerbGrid = { cardHTML, cellHTML, esc, PATTERN_ENDINGS, CLASS_ORDER };
})(this);
